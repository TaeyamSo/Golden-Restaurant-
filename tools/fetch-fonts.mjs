// Downloads the Arabic + Latin woff2 subsets from Google Fonts and writes
// assets/css/fonts.css pointing at the local copies (offline-friendly, no Google dependency).
// Run once: `node fetch-fonts.mjs` (from tools/).
import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fontsDir = join(root, 'assets', 'fonts');
mkdirSync(fontsDir, { recursive: true });

const CSS_URL = 'https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Arabic:wght@400;600&family=Reem+Kufi:wght@500..700&display=swap';
const KEEP = new Set(['arabic', 'latin']);
// a current Chrome UA makes Google serve woff2 with unicode-range subsets
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

const css = await (await fetch(CSS_URL, { headers: { 'User-Agent': UA } })).text();
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*{[^}]+})/g)];
let outCss = '/* generated by tools/fetch-fonts.mjs */\n';

for (const [, subset, block] of blocks) {
  if (!KEEP.has(subset)) continue;
  const family = block.match(/font-family:\s*'([^']+)'/)[1];
  const weight = block.match(/font-weight:\s*([\d ]+);/)[1].trim();
  const url = block.match(/url\((https:[^)]+\.woff2)\)/)[1];
  const file = `${family.toLowerCase().replace(/\s+/g, '-')}-${weight.replace(' ', '-')}-${subset}.woff2`;
  const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
  writeFileSync(join(fontsDir, file), buf);
  console.log(`${file.padEnd(46)} ${Math.round(buf.length / 1024)} KB`);
  outCss += `/* ${subset} */\n${block.replace(url, `../fonts/${file}`)}\n`;
}
writeFileSync(join(root, 'assets', 'css', 'fonts.css'), outCss);
